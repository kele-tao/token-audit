"""Accuracy harness for the vendored tokenizer approximation.

The golden set lives in tests/data/golden_tokens.json and is regenerated by
scripts/build_vocab_data.py from the reference tokenizer.  Running the
accuracy command counts every sample with our replay tokenizer and reports the
measured error.  Nothing is hard-coded here: if the tokenizer regresses, the
numbers move.
"""
from __future__ import annotations

import json
import pathlib
import statistics
from dataclasses import dataclass

from .tokenizer import get_tokenizer

GOLDEN_PATH = (
    pathlib.Path(__file__).resolve().parent.parent.parent
    / "tests"
    / "data"
    / "golden_tokens.json"
)
PACKAGED_GOLDEN = pathlib.Path(__file__).resolve().parent / "data" / "golden_tokens.json"


class AccuracyError(ValueError):
    """Raised when the golden set is missing or malformed."""


@dataclass(frozen=True)
class SampleResult:
    """One golden sample measured against the reference count."""

    sample_id: str
    encoding: str
    expected: int
    actual: int

    @property
    def error(self) -> float:
        """Signed relative error in percent."""
        if self.expected <= 0:
            return 0.0
        return 100.0 * (self.actual - self.expected) / self.expected

    @property
    def absolute_error(self) -> float:
        """Absolute relative error in percent."""
        return abs(self.error)


@dataclass
class AccuracyReport:
    """Aggregate accuracy for one encoding."""

    encoding: str
    samples: list[SampleResult]
    expected_total: int
    actual_total: int

    @property
    def total_error_pct(self) -> float:
        """Error on the corpus total, which is what matters for budgeting."""
        if not self.expected_total:
            return 0.0
        return 100.0 * (self.actual_total - self.expected_total) / self.expected_total

    @property
    def median_abs_error_pct(self) -> float:
        """Median per-sample absolute error."""
        return statistics.median(sample.absolute_error for sample in self.samples)

    @property
    def p95_abs_error_pct(self) -> float:
        """95th percentile per-sample absolute error."""
        errors = sorted(sample.absolute_error for sample in self.samples)
        index = min(len(errors) - 1, round(0.95 * (len(errors) - 1)))
        return errors[index]

    @property
    def exact_matches(self) -> int:
        """Number of samples counted exactly."""
        return sum(1 for sample in self.samples if sample.actual == sample.expected)

    @property
    def worst(self) -> list[SampleResult]:
        """Ten worst samples by absolute error, deterministic order."""
        return sorted(
            self.samples, key=lambda item: (-item.absolute_error, item.sample_id)
        )[:10]


def load_golden(path: pathlib.Path | None = None) -> dict:
    """Load the committed golden set."""
    for candidate in (path, GOLDEN_PATH, PACKAGED_GOLDEN):
        if candidate and candidate.exists():
            try:
                return json.loads(candidate.read_text(encoding="utf-8"))
            except json.JSONDecodeError as exc:
                raise AccuracyError(
                    "golden set %s is not valid JSON: %s" % (candidate, exc)
                ) from exc
    raise AccuracyError(
        "golden token set not found. Expected tests/data/golden_tokens.json; "
        "regenerate it with scripts/build_vocab_data.py."
    )


def measure(encoding: str, golden: dict | None = None) -> AccuracyReport:
    """Count every golden sample and aggregate the error."""
    data = golden if golden is not None else load_golden()
    samples = data.get("samples")
    if not isinstance(samples, list) or not samples:
        raise AccuracyError("golden set has no samples")
    tokenizer = get_tokenizer(encoding)
    results: list[SampleResult] = []
    expected_total = 0
    actual_total = 0
    for entry in samples:
        text = entry.get("text")
        expected = entry.get(encoding)
        if not isinstance(text, str) or not isinstance(expected, int):
            continue
        actual = tokenizer.count(text)
        expected_total += expected
        actual_total += actual
        results.append(
            SampleResult(
                sample_id=str(entry.get("id", len(results))),
                encoding=encoding,
                expected=expected,
                actual=actual,
            )
        )
    if not results:
        raise AccuracyError("golden set has no usable samples for %s" % encoding)
    return AccuracyReport(
        encoding=encoding,
        samples=results,
        expected_total=expected_total,
        actual_total=actual_total,
    )


def measure_all(golden: dict | None = None) -> list[AccuracyReport]:
    """Measure every vendored encoding in the golden set."""
    data = golden if golden is not None else load_golden()
    encodings = sorted(
        key for key in (data.get("encodings") or {}) if key in ("cl100k", "o200k")
    )
    return [measure(encoding, data) for encoding in encodings]


def render_accuracy(reports: list[AccuracyReport]) -> str:
    """Render the accuracy table as plain terminal text."""
    lines = [
        "token-audit accuracy  golden set %d samples" % len(reports[0].samples),
        "",
        "  %-8s %10s %10s %9s %9s %9s %9s"
        % ("encoding", "expected", "measured", "total", "median", "p95", "exact"),
    ]
    for report in reports:
        lines.append(
            "  %-8s %10s %10s %+8.2f%% %+8.2f%% %8.2f%% %5d/%d"
            % (
                report.encoding,
                format(report.expected_total, ","),
                format(report.actual_total, ","),
                report.total_error_pct,
                report.median_abs_error_pct,
                report.p95_abs_error_pct,
                report.exact_matches,
                len(report.samples),
            )
        )
    lines.append("")
    lines.append("  worst samples (absolute error):")
    for report in reports:
        for sample in report.worst[:5]:
            lines.append(
                "    %-8s %-6s expected %4d got %4d (%+6.2f%%)"
                % (
                    report.encoding,
                    sample.sample_id,
                    sample.expected,
                    sample.actual,
                    sample.error,
                )
            )
    lines.append("")
    lines.append(
        "  Counts replay a committed BPE merge table over a pure-Python port of the"
    )
    lines.append(
        "  reference pre-tokenizer. The port is tested against a held-out corpus but"
    )
    lines.append(
        "  is not guaranteed exact on text unlike anything in the golden set."
    )
    return "\n".join(lines)


def accuracy_json(reports: list[AccuracyReport]) -> str:
    """Render the accuracy table as JSON."""
    payload = {
        "samples": len(reports[0].samples) if reports else 0,
        "encodings": [
            {
                "encoding": report.encoding,
                "expected_total": report.expected_total,
                "measured_total": report.actual_total,
                "total_error_pct": round(report.total_error_pct, 4),
                "median_abs_error_pct": round(report.median_abs_error_pct, 4),
                "p95_abs_error_pct": round(report.p95_abs_error_pct, 4),
                "exact_matches": report.exact_matches,
            }
            for report in reports
        ],
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"
